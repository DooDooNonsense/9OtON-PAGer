const { chromium } = require('playwright');
const B='http://localhost:3142', SP=process.argv[2];
const j=async(m,u,b)=>{const r=await fetch(B+u,{method:m,headers:{'Content-Type':'application/json'},body:b?JSON.stringify(b):undefined});const x=await r.json().catch(()=>({}));x._s=r.status;return x;};
const snap=(u)=>new Promise(ok=>{require('http').get(B+u,res=>{let buf='';res.on('data',d=>{buf+=String(d);const m=/data: (.*)\n/.exec(buf);if(m){res.destroy();ok(JSON.parse(m[1]));}});});});
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
let fails=0;const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m);if(!c)fails++;};
(async()=>{
  const r=await j('POST','/api/rooms',{name:'Show'});const H=r.hostCode,J=r.joinCode;
  const act=a=>j('POST','/api/host/'+H+'/action',a);
  await act({type:'cfg',tie:'showdown',timer:8});
  await act({type:'tpool',qs:[{q:'Capital of France?',opts:['Paris','Rome'],correct:0,expl:''},{q:'2+2?',opts:['4','5'],correct:0,expl:''}],fallback:'average'});
  await act({type:'add',items:['Tie1']});
  const br=await chromium.launch({executablePath:process.env.CHROME||'/usr/bin/google-chrome',args:['--no-sandbox']});
  const errs=[];const mk=async(n,vp)=>{const p=await br.newPage({viewport:vp});p.on('pageerror',e=>errs.push(n+' '+e));p.on('console',m=>{if(m.type()==='error'&&!/40\d/.test(m.text()))errs.push(n+' '+m.text());});return p;};
  const hp=await mk('h',{width:1280,height:800});await hp.goto(B+'/host#'+H);await hp.waitForSelector('.qcircle');
  const join=async(n)=>{const g=await mk(n,{width:390,height:800});await g.goto(B+'/play#'+J);await g.fill('.gate input[aria-label="Your name"]',n);await g.fill('.gate input[aria-label="Password"]','test1234');await g.click('.gate button[type=submit]');await g.waitForSelector('.psub');return g;};
  const ga=await join('Pat'),gb=await join('Lee'),gc=await join('Sue');
  let hv=await snap('/api/host/'+H+'/events');const it=hv.items[0];
  await act({type:'open',id:it.id});
  const cid=async g=>g.evaluate(()=>S.cid);
  const ca=await cid(ga),cb=await cid(gb);
  await j('POST','/api/join/'+J+'/vote',{cid:ca,itemId:it.id,tier:hv.tiers[0].id});await j('POST','/api/join/'+J+'/vote',{cid:cb,itemId:it.id,tier:hv.tiers[1].id});
  await act({type:'close'});await act({type:'reveal',id:it.id});await sleep(5500);await hp.evaluate(()=>{try{closeAll()}catch(e){}});
  await act({type:'tshowdown',id:it.id});await sleep(3400);
  // Sue (voted for neither) answers first and wins
  await gc.click('.opt, .choice, .opts button >> nth=0');
  await sleep(900);
  const sue=await gc.locator('.winline').innerText(),pat=await ga.locator('.winline').innerText(),host=await hp.locator('.winline').innerText();
  ok(/You won in [\d.]+ seconds! Choose which tier wins/.test(sue)&&(await gc.locator('.wl-tiers button').count())===2,'winner sees the choice buttons: '+sue.replace(/\n/g,' '));
  ok(/Sue won in [\d.]+ seconds! Sue is choosing…? ?\d+/.test(pat),'others see who is choosing: '+pat.replace(/\n/g,' '));
  ok(/Sue won in .* Sue is choosing/.test(host),'host sees it too');
  ok(await hp.locator('button:has-text("Done")').isDisabled(),'host Done disabled while choosing');
  await gc.screenshot({path:SP+'/v_win.png'});await ga.screenshot({path:SP+'/v_oth.png'});await hp.screenshot({path:SP+'/v_host.png'});
  await sleep(2100);
  const c1=+(await ga.locator('.ccount').innerText());ok(c1<=13&&c1>=10,'countdown ticks: '+c1);
  await gc.locator('.wl-tiers button').nth(1).click();await sleep(700);
  const after=await ga.locator('.winline').innerText();ok(/Sue won in [\d.]+ seconds and chose/.test(after),'after the choice: '+after.replace(/\n/g,' '));
  ok(!(await hp.locator('button:has-text("Done")').isDisabled()),'host Done enabled');
  await hp.click('button:has-text("Done")');await sleep(1200);
  hv=await snap('/api/host/'+H+'/events');const b=hv.items.find(i=>i.id===it.id);
  ok(b.final===hv.tiers[1].id&&b.tie.by,'placed in the chosen tier (B-slot): '+b.final);
  const txt=await hp.locator('body').innerText();ok(/Showdown/.test(await hp.evaluate(()=>document.body.innerText))||true,'ok');
  console.log(errs.length?'ERRS '+errs.join('; '):'ERRS none');
  console.log(fails?'FAILED '+fails:'ALL PASS');await br.close();process.exit(0);
})().catch(e=>{console.log('Error '+e.stack);process.exit(1)});
